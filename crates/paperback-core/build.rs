use std::{
	env,
	fmt::Write as _,
	fs,
	io::Write as _,
	path::{Path, PathBuf},
};

use flate2::{Compression, write::GzEncoder};

fn main() {
	shipfitter::build::embed_commit_info("PAPERBACK");
	pack_braille_tables();
}

/// Gzips each liblouis table on its own, so opening a book unpacks only its table and what that includes rather than all 13 MB. Writes the packed tables as one file, and a Rust index of where each lies plus the list of tables people choose from, whose names are read here so listing them unpacks nothing.
fn pack_braille_tables() {
	let dir = Path::new("liblouis/tables");
	println!("cargo::rerun-if-changed={}", dir.display());
	let mut paths: Vec<PathBuf> = fs::read_dir(dir)
		.expect("read liblouis/tables")
		.map(|entry| entry.expect("list liblouis/tables").path())
		.collect();
	// By name as a string, since the parser finds a table by binary search.
	paths.sort_by(|a, b| a.file_name().cmp(&b.file_name()));
	let mut packed = Vec::new();
	let mut index = String::from(
		"#[allow(clippy::unreadable_literal, reason = \"generated byte offsets\")]\nstatic PACKED_INDEX: &[(&str, usize, usize)] = &[\n",
	);
	let mut choosable = Vec::new();
	for path in paths {
		let name = path.file_name().and_then(|name| name.to_str()).expect("table names are UTF-8").to_owned();
		let contents = fs::read(&path).expect("read a liblouis table");
		let mut encoder = GzEncoder::new(Vec::new(), Compression::best());
		encoder.write_all(&contents).expect("pack a table");
		let member = encoder.finish().expect("pack a table");
		writeln!(index, "\t({name:?}, {}, {}),", packed.len(), member.len()).expect("write the index");
		packed.extend_from_slice(&member);
		if [".ctb", ".utb", ".tbl"].iter().any(|extension| name.ends_with(extension)) {
			let source = String::from_utf8_lossy(&contents);
			let named = |prefix: &str| {
				source
					.lines()
					.find_map(|line| line.strip_prefix(prefix))
					.map(str::trim)
					.filter(|name| !name.is_empty())
					.map(str::to_owned)
			};
			let display_name =
				named("#-display-name:").or_else(|| named("# liblouis:")).unwrap_or_else(|| name.clone());
			choosable.push((display_name, name));
		}
	}
	index.push_str("];\n\nstatic CHOOSABLE: &[BrailleTable] = &[\n");
	// Without regard to case, or the tables named only by a lowercase file name would all come after the named ones.
	choosable.sort_by_cached_key(|(display_name, file_name)| (display_name.to_lowercase(), file_name.clone()));
	for (display_name, file_name) in choosable {
		writeln!(index, "\tBrailleTable {{ file_name: {file_name:?}, display_name: {display_name:?} }},")
			.expect("write the list");
	}
	index.push_str("];\n");
	let out = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR is set"));
	fs::write(out.join("liblouis-tables.bin"), packed).expect("write packed tables");
	fs::write(out.join("liblouis-tables.rs"), index).expect("write the table index");
}
