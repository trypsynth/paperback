#[derive(Parser)]
#[command(
	name = "ios",
	bin_name = "cargo ios",
	about = "Build the iOS XCFramework and Swift bindings",
	args_conflicts_with_subcommands = true
)]
struct IosArgs {
	/// Build in release mode
	#[arg(long)]
	release: bool,
	#[command(subcommand)]
	command: Option<IosCommand>,
}

#[derive(Subcommand)]
enum IosCommand {
	/// Build and run Paperback on a simulator or device
	Run(RunArgs),
}

#[derive(Args)]
struct RunArgs {
	/// Run on a paired iPhone or iPad, optionally selected by name or UDID
	#[arg(long, value_name = "NAME", conflicts_with = "simulator")]
	// Clap uses nested Options for an absent flag, a bare flag, and a flag with a value.
	#[allow(clippy::option_option)]
	device: Option<Option<String>>,
	/// Select a simulator by name or UDID (default: the booted one, else the newest iPhone)
	#[arg(long, value_name = "NAME")]
	// Clap must track flag presence to reject --device together with a bare --simulator.
	#[allow(clippy::option_option)]
	simulator: Option<Option<String>>,
	/// Sign with this team instead of the one signed in to Xcode
	#[arg(long, value_name = "ID", requires = "device")]
	team: Option<String>,
	/// Print app output and stay attached until it exits
	#[arg(long)]
	console: bool,
	/// Build in release mode
	#[arg(long)]
	release: bool,
}

pub fn ios() -> Result<(), Box<dyn Error>> {
	let args = IosArgs::parse_from(env::args_os().skip(1));
	if let Some(IosCommand::Run(args)) = args.command {
		return run(args);
	}
	prepare(args.release)?;
	println!("iOS build complete.");
	println!("  XCFramework: ios/paperbackFFI.xcframework");
	println!("  Swift bindings: ios/Paperback/Generated/paperback.swift");
	println!("  Localizable.strings: ios/Paperback/<lang>.lproj/Localizable.strings");
	println!("  Add both XCFramework and Swift bindings to the Xcode project to use the Rust core.");
	Ok(())
}

/// Builds the Rust libraries and generates bindings, translations, help, and the local signing config.
fn prepare(release: bool) -> Result<(), Box<dyn Error>> {
	let cargo = env::var("CARGO").unwrap_or_else(|_| "cargo".to_string());
	let root = project_root();
	fs::write(
		root.join("ios/Config/Local.xcconfig"),
		format!(
			// #include? means include if exists; only for 3rd-party contributors for whom we generate this file.
			// Using a global file here makes sure we don't waste the weekly bundle ID limit for free accounts unnecessarily, even with multiple checkouts / worktrees.
			"// Generated by cargo ios. Signing settings are shared across checkouts.\n#include? \"{}\"\n",
			mac_signing_file().display()
		),
	)?;
	let status =
		Command::new("rustup").args(["target", "add", "aarch64-apple-ios", "aarch64-apple-ios-sim"]).status()?;
	if !status.success() {
		return Err("rustup couldn't add the iOS targets".into());
	}
	let generated_dir = root.join("ios/Paperback/Generated");
	fs::create_dir_all(&generated_dir)?;
	println!("Generating Swift bindings via uniffi-bindgen...");
	let ffi_library = build_host_ffi_library(&cargo)?.to_string_lossy().into_owned();
	let status = Command::new(&cargo)
		.current_dir(&root)
		.args([
			"run",
			"-p",
			"paperback-core",
			"--features",
			"uniffi",
			"--bin",
			"uniffi-bindgen",
			"--",
			"generate",
			"--library",
			&ffi_library,
			"--language",
			"swift",
			"--out-dir",
			"ios/Paperback/Generated",
			"--no-format",
		])
		.status()?;
	if !status.success() {
		return Err("uniffi-bindgen Swift generation failed".into());
	}
	let profile = if release { "release" } else { "debug" };
	let mut build_args =
		vec!["rustc", "-p", "paperback-core", "--features", MOBILE_CORE_FEATURES, "--lib", "--crate-type", "staticlib"];
	if release {
		build_args.push("--release");
	}
	// Without the simulator slice xcodebuild fails with "no library for this platform was found".
	for (target, label) in [("aarch64-apple-ios", "device"), ("aarch64-apple-ios-sim", "simulator")] {
		println!("Building for {target} ({label})...");
		let status = Command::new(&cargo).current_dir(&root).args(&build_args).args(["--target", target]).status()?;
		if !status.success() {
			return Err(format!("cargo build for {target} failed").into());
		}
	}
	let headers_dir = root.join("ios/Paperback/Generated");
	let device_lib = root.join(format!("target/aarch64-apple-ios/{profile}/libpaperback_core.a"));
	let simulator_lib = root.join(format!("target/aarch64-apple-ios-sim/{profile}/libpaperback_core.a"));
	let xcframework_out = root.join("ios/paperbackFFI.xcframework");
	if xcframework_out.exists() {
		fs::remove_dir_all(&xcframework_out)?;
	}
	println!("Creating paperbackFFI.xcframework...");
	let status = Command::new("xcodebuild")
		.args(["-create-xcframework"])
		.arg("-library")
		.arg(&device_lib)
		.arg("-headers")
		.arg(&headers_dir)
		.arg("-library")
		.arg(&simulator_lib)
		.arg("-headers")
		.arg(&headers_dir)
		.arg("-output")
		.arg(&xcframework_out)
		.status()?;
	if !status.success() {
		return Err("xcodebuild -create-xcframework failed".into());
	}
	let po_dir = root.join("po");
	let ios_dir = root.join("ios/Paperback");
	if po_dir.is_dir() {
		if let Err(e) = patois_build::gen_ios_strings(&po_dir, &ios_dir) {
			println!("Warning: could not generate Localizable.strings: {e}");
		}
		// iOS only matches a device's language to BCP-47 folder names, not po stems; keep in sync with knownRegions in project.pbxproj and the Localizable.strings variant group.
		for (from, to) in [("pt_br", "pt-BR"), ("zh_CN", "zh-Hans")] {
			let from_dir = ios_dir.join(format!("{from}.lproj"));
			let to_dir = ios_dir.join(format!("{to}.lproj"));
			if from_dir.is_dir() {
				let _ = fs::remove_dir_all(&to_dir);
				fs::rename(&from_dir, &to_dir)?;
			}
		}
	}
	crate::docs::write_app_readmes(&ios_dir.join("Readmes"))?;
	Ok(())
}

enum Destination {
	Device(Option<String>),
	Simulator(Option<String>),
}

enum RunTarget {
	Device(Device),
	Simulator(Simulator),
}

/// Device list from `xcrun devicectl list devices --json-output -`.
#[derive(Deserialize)]
struct DeviceList {
	result: DeviceListResult,
}

#[derive(Deserialize)]
struct DeviceListResult {
	devices: Vec<Device>,
}

#[derive(Deserialize)]
struct Device {
	/// `devicectl` uses this ID; `xcodebuild` uses the hardware UDID.
	identifier: String,
	#[serde(rename = "deviceProperties")]
	properties: DeviceProperties,
	#[serde(rename = "hardwareProperties")]
	hardware: HardwareProperties,
	#[serde(rename = "connectionProperties")]
	connection: ConnectionProperties,
}

#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
struct DeviceProperties {
	name: String,
	/// Absent on simulators included in the device list.
	developer_mode_status: Option<String>,
}

#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
struct HardwareProperties {
	platform: String,
	reality: String,
	udid: String,
}

#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
struct ConnectionProperties {
	pairing_state: String,
}

/// `xcrun simctl list devices available --json`, keyed by runtime, like
/// `com.apple.CoreSimulator.SimRuntime.iOS-27-2`.
#[derive(Deserialize)]
struct SimulatorList {
	devices: BTreeMap<String, Vec<Simulator>>,
}

#[derive(Deserialize)]
struct Simulator {
	udid: String,
	name: String,
	state: String,
}

/// One entry of Xcode's `IDEProvisioningTeams` preference.
#[derive(Deserialize)]
struct XcodeTeam {
	#[serde(rename = "teamID")]
	id: String,
	#[serde(rename = "teamName")]
	name: String,
	#[serde(rename = "teamType")]
	kind: String,
}

/// Builds and launches the app. No interactive prompts, so agents don't waste time waiting for something that
/// can never finish without further input. Errors cause an immediate exit and provide an actionable message
/// for agents and humans alike.
fn run(args: RunArgs) -> Result<(), Box<dyn Error>> {
	let RunArgs { release, console, team, device, simulator } = args;
	let destination = match device {
		Some(name) => Destination::Device(name),
		None => Destination::Simulator(simulator.flatten()),
	};
	let root = project_root();
	// Resolve the target and signing before starting the Rust build to report setup errors early.
	let target = match destination {
		Destination::Device(name) => {
			let device = find_device(name.as_deref())?;
			set_up_signing(&root, team.as_deref())?;
			RunTarget::Device(device)
		}
		Destination::Simulator(name) => RunTarget::Simulator(find_simulator(name.as_deref())?),
	};
	prepare(release)?;
	let configuration = if release { "Release" } else { "Debug" };
	let (name, udid, platform) = match &target {
		RunTarget::Device(device) => (device.properties.name.clone(), device.hardware.udid.clone(), "iphoneos"),
		RunTarget::Simulator(simulator) => (simulator.name.clone(), simulator.udid.clone(), "iphonesimulator"),
	};
	println!("Building Paperback for {name}...");
	// Set the output directory so we can locate the app after building.
	let derived_data = root.join("target/ios-derived-data");
	let mut xcodebuild = Command::new("xcodebuild");
	xcodebuild
		.current_dir(&root)
		.args(["-project", "ios/Paperback.xcodeproj", "-scheme", "Paperback", "-configuration", configuration])
		.args(["-destination", &format!("id={udid}")])
		.arg("-derivedDataPath")
		.arg(&derived_data)
		.arg("-quiet");
	if let RunTarget::Device(_) = target {
		// Allow Xcode to set up signing and register the device using the signed-in account, if not done already.
		xcodebuild.args(["-allowProvisioningUpdates", "-allowProvisioningDeviceRegistration"]);
	}
	if !xcodebuild.arg("build").status()?.success() {
		if matches!(target, RunTarget::Device(_)) {
			return Err(
				"xcodebuild failed. For account or provisioning errors, sign in again under Xcode > Settings > \
			 Accounts. Xcode can list an account whose login has expired."
					.into(),
			);
		}
		return Err("xcodebuild failed".into());
	}
	let app = derived_data.join(format!("Build/Products/{configuration}-{platform}/Paperback.app"));
	let output = Command::new("plutil")
		.args(["-extract", "CFBundleIdentifier", "raw", "-o", "-"])
		.arg(app.join("Info.plist"))
		.output()?;
	if !output.status.success() {
		return Err(format!("couldn't read the bundle ID of {}", app.display()).into());
	}
	let bundle_id = String::from_utf8(output.stdout)?.trim().to_string();
	match target {
		RunTarget::Device(device) => {
			println!("Installing on {name}...");
			let status = Command::new("xcrun")
				.args(["devicectl", "device", "install", "app", "--device", &device.identifier])
				.arg(&app)
				.status()?;
			if !status.success() {
				return Err(format!(
					"couldn't install on {name}. If it's connected over the network, check that it's unlocked and on \
					 the same network as this Mac."
				)
				.into());
			}
			let mut launch = Command::new("xcrun");
			launch.args([
				"devicectl",
				"device",
				"process",
				"launch",
				"--device",
				&device.identifier,
				"--terminate-existing",
			]);
			if console {
				launch.arg("--console");
			}
			if !launch.arg(&bundle_id).status()?.success() {
				return Err(format!(
					"Paperback is installed on {name} but could not start. If iOS asks you to trust the developer, \
					 open Settings > General > VPN & Device Management on the device, trust your Apple Development \
					 certificate, and try again."
				)
				.into());
			}
		}
		RunTarget::Simulator(simulator) => {
			if simulator.state != "Booted" {
				let status = Command::new("xcrun").args(["simctl", "boot", &simulator.udid]).status()?;
				if !status.success() {
					return Err(format!("couldn't boot the {name} simulator").into());
				}
			}
			// Xcode 27 uses Device Hub; older versions use Simulator. Opening the viewer is optional:
			// the simulator can run without a window, and sandbox restrictions may block `open`.
			let output = Command::new("xcode-select").arg("-p").output()?;
			let developer_dir = PathBuf::from(String::from_utf8(output.stdout)?.trim());
			let viewer =
				[developer_dir.join("../Applications/DeviceHub.app"), developer_dir.join("Applications/Simulator.app")]
					.into_iter()
					.find(|app| app.exists());
			if !viewer
				.is_some_and(|viewer| Command::new("open").arg(viewer).status().is_ok_and(|status| status.success()))
			{
				println!(
					"Could not open the simulator window. Open Device Hub or Simulator to view it. If you are an agent, this might be a sandbox issue."
				);
			}
			let status = Command::new("xcrun").args(["simctl", "install", &simulator.udid]).arg(&app).status()?;
			if !status.success() {
				return Err(format!("couldn't install on the {name} simulator").into());
			}
			let mut launch = Command::new("xcrun");
			launch.args(["simctl", "launch", "--terminate-running-process"]);
			if console {
				launch.arg("--console-pty");
			}
			if !launch.args([&simulator.udid, &bundle_id]).status()?.success() {
				return Err(format!("couldn't start Paperback on the {name} simulator").into());
			}
		}
	}
	println!("Paperback is running on {name}.");
	Ok(())
}

/// Selects a paired device by name or ID, or the only paired device if neither is given.
fn find_device(name: Option<&str>) -> Result<Device, Box<dyn Error>> {
	let output =
		Command::new("xcrun").args(["devicectl", "list", "devices", "--quiet", "--json-output", "-"]).output()?;
	if !output.status.success() {
		return Err("xcrun devicectl couldn't list devices".into());
	}
	let list: DeviceList = serde_json::from_slice(&output.stdout)?;
	let mut devices: Vec<Device> = list
		.result
		.devices
		.into_iter()
		.filter(|device| {
			device.hardware.platform == "iOS"
				&& device.hardware.reality == "physical"
				&& device.connection.pairing_state == "paired"
		})
		.collect();
	if let Some(name) = name {
		devices.retain(|device| {
			device.properties.name == name || device.identifier == name || device.hardware.udid == name
		});
	}
	if devices.len() > 1 {
		let names = devices
			.iter()
			.map(|device| format!("  --device \"{}\"", device.properties.name))
			.collect::<Vec<_>>()
			.join("\n");
		return Err(format!("several devices are paired; pick one:\n{names}").into());
	}
	let device = devices.pop().ok_or_else(|| match name {
		Some(name) => format!("no paired device matches {name}. Run `xcrun devicectl list devices` to list devices"),
		None => "no paired iPhone or iPad. Connect one with a cable, unlock it, tap Trust, and pair it in Xcode's \
		         Devices window or with `xcrun devicectl manage pair --device <name>`."
			.to_string(),
	})?;
	if device.properties.developer_mode_status.as_deref() != Some("enabled") {
		return Err(format!(
			"Developer Mode is off on {}. On the device, open Settings > Privacy & Security > Developer Mode, turn it \
			 on and let it restart.",
			device.properties.name
		)
		.into());
	}
	Ok(device)
}

/// Selects a simulator by name or UDID, preferring the newest iOS runtime.
/// Defaults to the booted simulator, then the first iPhone on the newest runtime.
fn find_simulator(name: Option<&str>) -> Result<Simulator, Box<dyn Error>> {
	let output = Command::new("xcrun").args(["simctl", "list", "devices", "available", "--json"]).output()?;
	if !output.status.success() {
		return Err("xcrun simctl couldn't list simulators".into());
	}
	let list: SimulatorList = serde_json::from_slice(&output.stdout)?;
	// Runtime keys end in the iOS version, like `iOS-27-2`, sometimes followed by a device model.
	let mut simulators: Vec<((u32, u32), Simulator)> = list
		.devices
		.into_iter()
		.filter_map(|(runtime, simulators)| {
			let mut parts = runtime.strip_prefix("com.apple.CoreSimulator.SimRuntime.iOS-")?.split('-');
			let version = (parts.next()?.parse().ok()?, parts.next()?.parse().ok()?);
			Some(simulators.into_iter().map(move |simulator| (version, simulator)))
		})
		.flatten()
		.collect();
	simulators.sort_by_key(|(version, _)| Reverse(*version));
	let mut simulators = simulators.into_iter().map(|(_, simulator)| simulator);
	if let Some(name) = name {
		return simulators.find(|simulator| simulator.name == name || simulator.udid == name).ok_or_else(|| {
			format!("no iOS simulator matches {name}. Run `xcrun simctl list devices available` to list simulators")
				.into()
		});
	}
	let mut simulators: Vec<Simulator> = simulators.collect();
	let booted: Vec<usize> = (0..simulators.len()).filter(|&index| simulators[index].state == "Booted").collect();
	let index = match booted.as_slice() {
		[] => simulators
			.iter()
			.position(|simulator| simulator.name.starts_with("iPhone"))
			.ok_or("no iPhone simulator is installed; add an iOS runtime in Xcode > Settings > Components")?,
		[index] => *index,
		several => {
			let choices = several
				.iter()
				.map(|&index| format!("  --simulator {}  ({})", simulators[index].udid, simulators[index].name))
				.collect::<Vec<_>>()
				.join("\n");
			return Err(format!("several simulators are booted; pick one:\n{choices}").into());
		}
	};
	Ok(simulators.swap_remove(index))
}

/// Saves signing overrides when using a team other than the project's default.
/// The bundle ID depends only on the team so checkouts reuse it: free teams can register 10 App IDs per week.
fn set_up_signing(root: &Path, team: Option<&str>) -> Result<(), Box<dyn Error>> {
	let mac_file = mac_signing_file();
	if team.is_none() && mac_file.exists() {
		return Ok(());
	}
	let checked_in_team = checked_in_signing_value(root, "DEVELOPMENT_TEAM")?;
	let team = if let Some(team) = team {
		team.to_string()
	} else {
		let teams = xcode_teams()?;
		if teams.iter().any(|team| team.id == checked_in_team) {
			checked_in_team.clone()
		} else {
			match teams.as_slice() {
				[] => {
					return Err("no Apple account is signed in to Xcode. Open Xcode > Settings > Accounts and add \
						            yours. A free Apple account works."
						.into());
				}
				[team] => team.id.clone(),
				teams => {
					let choices = teams
						.iter()
						.map(|team| format!("  --team {}  ({}, {})", team.id, team.name, team.kind))
						.collect::<Vec<_>>()
						.join("\n");
					return Err(format!("several teams are signed in to Xcode; pick one:\n{choices}").into());
				}
			}
		}
	};
	if team == checked_in_team {
		if mac_file.exists() {
			fs::remove_file(&mac_file)?;
		}
		return Ok(());
	}
	let bundle_id = format!("dev.paperback.ios.{}", team.to_lowercase());
	fs::create_dir_all(mac_file.parent().expect("the file is inside ~/.config"))?;
	fs::write(
		&mac_file,
		format!(
			"// Generated by cargo ios run --device. Shared across Paperback checkouts.\n\
			 // Reuse one bundle ID per team to stay within the free account's App ID limit.\n\
			 DEVELOPMENT_TEAM = {team}\n\
			 PAPERBACK_BUNDLE_ID = {bundle_id}\n"
		),
	)?;
	println!("Signing as team {team} with bundle ID {bundle_id}, saved in {}", mac_file.display());
	Ok(())
}

/// Reads Xcode's undocumented `IDEProvisioningTeams` preference, which maps accounts to their teams.
fn xcode_teams() -> Result<Vec<XcodeTeam>, Box<dyn Error>> {
	let preferences = Command::new("defaults").args(["export", "com.apple.dt.Xcode", "-"]).output()?;
	let mut plutil = Command::new("plutil")
		.args(["-extract", "IDEProvisioningTeams", "json", "-o", "-", "-"])
		.stdin(Stdio::piped())
		.stdout(Stdio::piped())
		.stderr(Stdio::null())
		.spawn()?;
	plutil.stdin.take().expect("stdin is piped").write_all(&preferences.stdout)?;
	let output = plutil.wait_with_output()?;
	// The preference only exists once an account has been signed in.
	if !output.status.success() {
		return Ok(Vec::new());
	}
	let accounts: BTreeMap<String, Vec<XcodeTeam>> = serde_json::from_slice(&output.stdout)?;
	// Two signed-in accounts can belong to the same team.
	let teams: BTreeMap<String, XcodeTeam> =
		accounts.into_values().flatten().map(|team| (team.id.clone(), team)).collect();
	Ok(teams.into_values().collect())
}

/// Reads a `NAME = value` line from `ios/Config/Signing.xcconfig`.
fn checked_in_signing_value(root: &Path, name: &str) -> Result<String, Box<dyn Error>> {
	let xcconfig = fs::read_to_string(root.join("ios/Config/Signing.xcconfig"))?;
	let prefix = format!("{name} = ");
	let value = xcconfig
		.lines()
		.find_map(|line| line.strip_prefix(&prefix))
		.ok_or_else(|| format!("ios/Config/Signing.xcconfig doesn't set {name}"))?;
	Ok(value.to_string())
}

/// Shared signing config. Each checkout includes its absolute path because xcconfig includes cannot expand `~`.
fn mac_signing_file() -> PathBuf {
	home_dir().join(".config/paperback-dev/ios-signing.xcconfig")
}

pub fn ios_release() -> Result<(), Box<dyn Error>> {
	let upload = env::args().any(|a| a == "--upload");
	let root = project_root();
	let ios_dir = root.join("ios");
	let archive_path = root.join("target/Paperback.xcarchive");
	let export_path = root.join("target/PaperbackExport");
	let export_options = ios_dir.join("ExportOptions.plist");
	if !export_options.exists() {
		return Err("ios/ExportOptions.plist not found".into());
	}
	// Command-line settings override local signing config so App Store builds use the project's team and bundle ID.
	let team = checked_in_signing_value(&root, "DEVELOPMENT_TEAM")?;
	let bundle_id = checked_in_signing_value(&root, "PAPERBACK_BUNDLE_ID")?;
	println!("Archiving Paperback.xcodeproj...");
	let status = Command::new("xcodebuild")
		.args([
			"archive",
			"-project",
			&ios_dir.join("Paperback.xcodeproj").to_string_lossy(),
			"-scheme",
			"Paperback",
			"-destination",
			"generic/platform=iOS",
			"-archivePath",
			&archive_path.to_string_lossy(),
			&format!("DEVELOPMENT_TEAM={team}"),
			&format!("PAPERBACK_BUNDLE_ID={bundle_id}"),
		])
		.status()?;
	if !status.success() {
		return Err("xcodebuild archive failed".into());
	}
	println!("Exporting IPA...");
	let _ = fs::remove_dir_all(&export_path);
	let status = Command::new("xcodebuild")
		.args([
			"-exportArchive",
			"-archivePath",
			&archive_path.to_string_lossy(),
			"-exportPath",
			&export_path.to_string_lossy(),
			"-exportOptionsPlist",
			&export_options.to_string_lossy(),
		])
		.status()?;
	if !status.success() {
		return Err("xcodebuild -exportArchive failed".into());
	}
	let ipa = export_path.join("Paperback.ipa");
	if !ipa.exists() {
		return Err(format!("IPA not found at {}", ipa.display()).into());
	}
	println!("IPA ready: {}", ipa.display());
	if upload {
		upload_ipa(&ipa)?;
	} else {
		println!("To upload, run:  cargo xtask ios-release --upload");
		println!("Or drag {} into Transporter or Xcode Organizer.", ipa.display());
	}
	Ok(())
}

/// Uses the macOS notarization step's API key and variables, so there's one set of credentials to keep.
/// A missing key is reported here because altool's own message for it is easy to miss.
fn upload_ipa(ipa: &Path) -> Result<(), Box<dyn Error>> {
	let key_id = env::var("APPSTORE_API_KEY_ID").unwrap_or_default().trim().to_string();
	let issuer_id = env::var("APPSTORE_API_ISSUER_ID").unwrap_or_default().trim().to_string();
	if key_id.is_empty() || issuer_id.is_empty() {
		return Err("APPSTORE_API_KEY_ID and APPSTORE_API_ISSUER_ID must both be set to upload. 			They are the same values the macOS notarization step uses."
			.into());
	}
	let key_name = format!("AuthKey_{key_id}.p8");
	let searched = [
		PathBuf::from("private_keys"),
		home_dir().join("private_keys"),
		home_dir().join(".private_keys"),
		home_dir().join(".appstoreconnect/private_keys"),
	];
	if !searched.iter().any(|dir| dir.join(&key_name).exists()) {
		let places = searched.iter().map(|d| d.display().to_string()).collect::<Vec<_>>().join(", ");
		return Err(format!("{key_name} not found. altool looks for it in: {places}").into());
	}
	println!("Uploading to App Store Connect...");
	let status = Command::new("xcrun")
		.args([
			"altool",
			"--upload-app",
			"--type",
			"ios",
			"--file",
			&ipa.to_string_lossy(),
			"--apiKey",
			&key_id,
			"--apiIssuer",
			&issuer_id,
		])
		.status()?;
	if !status.success() {
		return Err(format!(
			"altool upload failed. The IPA is still at {}, so it can go through Transporter instead.",
			ipa.display()
		)
		.into());
	}
	println!("Upload complete. The build appears in TestFlight once Apple finishes processing it.");
	Ok(())
}

fn home_dir() -> PathBuf {
	PathBuf::from(env::var("HOME").unwrap_or_default())
}

#[cfg(test)]
mod tests {
	use clap::{CommandFactory, error::ErrorKind};

	use super::*;

	#[test]
	fn cli_definition_is_consistent() {
		IosArgs::command().debug_assert();
	}

	#[test]
	fn build_options_parse() {
		for (args, release) in [(vec!["ios"], false), (vec!["ios", "--release"], true)] {
			let parsed = IosArgs::try_parse_from(args).unwrap();
			assert_eq!(parsed.release, release);
			assert!(parsed.command.is_none());
		}
	}

	#[test]
	fn run_preserves_destination_and_options() {
		for (flag, name) in [
			("--device", None),
			("--device", Some("My iPhone")),
			("--simulator", None),
			("--simulator", Some("iPhone 17")),
		] {
			let mut args = vec!["ios", "run", flag];
			args.extend(name);
			args.extend(["--release", "--console"]);
			if flag == "--device" {
				args.extend(["--team", "TEAM"]);
			}
			let parsed = IosArgs::try_parse_from(args).unwrap();
			let Some(IosCommand::Run(run)) = parsed.command else { panic!("expected run") };
			let (selected, other) =
				if flag == "--device" { (run.device, run.simulator) } else { (run.simulator, run.device) };
			assert_eq!(selected, Some(name.map(str::to_string)));
			assert_eq!(other, None);
			assert_eq!(run.team.as_deref(), (flag == "--device").then_some("TEAM"));
			assert!(run.release);
			assert!(run.console);
		}
		let parsed = IosArgs::try_parse_from(["ios", "run"]).unwrap();
		let Some(IosCommand::Run(run)) = parsed.command else { panic!("expected run") };
		assert!(run.device.is_none() && run.simulator.is_none());
		assert!(!run.release && !run.console);
	}

	#[test]
	fn invalid_options_fail_during_parsing() {
		for (args, kind) in [
			(vec!["run", "--device", "--simulator"], ErrorKind::ArgumentConflict),
			(vec!["run", "--simulator", "--device"], ErrorKind::ArgumentConflict),
			(vec!["run", "--team", "TEAM"], ErrorKind::MissingRequiredArgument),
			(vec!["run", "--device", "--team"], ErrorKind::InvalidValue),
			(vec!["run", "--device", "--team", "--release"], ErrorKind::InvalidValue),
			(vec!["--typo"], ErrorKind::UnknownArgument),
			(vec!["run", "--typo"], ErrorKind::UnknownArgument),
			(vec!["unknown-command"], ErrorKind::InvalidSubcommand),
		] {
			let error = IosArgs::try_parse_from(std::iter::once("ios").chain(args.iter().copied()))
				.err()
				.unwrap_or_else(|| panic!("accepted {args:?}"));
			assert_eq!(error.kind(), kind, "{args:?}: {error}");
		}
	}

	#[test]
	fn help_is_available_for_build_and_run() {
		for args in [vec!["ios", "--help"], vec!["ios", "run", "--help"]] {
			let error = IosArgs::try_parse_from(args).err().unwrap();
			assert_eq!(error.kind(), ErrorKind::DisplayHelp);
		}
	}
}
